//! Ghostty configuration schema: types, metadata and documentation.
//! Generated from Ghostty default configuration covering all 200 options.
//!
//! User-facing copy is bilingual: see [`Text`].

use crate::i18n::Text;

#[derive(Clone, Copy, Debug, PartialEq)]
pub enum Kind {
    Bool,
    Int { min: i64, max: i64 },
    Float { min: f64, max: f64 },
    Enum(&'static [&'static str]),
    Color { special: &'static [&'static str] },
    Text,
    /// Repeatable key (font-family, env, keybind, palette, ...).
    List,
    /// Comma list where an item may be prefixed with `no-`.
    Flags(&'static [&'static str]),
}

pub struct Opt {
    pub key: &'static str,
    pub label: Text,
    pub doc: Text,
    pub kind: Kind,
    /// Short usage hint shown under the widget.
    pub hint: Text,
    /// Non-empty when the option only applies to one platform.
    pub platform: &'static str,
}

impl Opt {
    /// `true` when the key may appear more than once in the file.
    pub fn repeatable(&self) -> bool {
        matches!(self.kind, Kind::List)
    }
}

pub struct Category {
    pub label: Text,
    pub desc: Text,
    pub keys: &'static [&'static str],
}

